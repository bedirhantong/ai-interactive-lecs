import fs from "node:fs";
import path from "node:path";
import { describe, expect, it } from "vitest";
import { loadContent } from "@/lib/content/loader";
import { type Cell, lessonSchema } from "@/lib/content/schema";
import { labsOfCells } from "@/lib/labs";
import { colabOpenUrl } from "@/lib/labs/colab/launcher";
import { MAX_REPORT_BYTES, parseTrainingReport } from "@/lib/labs/colab/report";

// Produced by really executing the notebook: scripts/verify_colab_notebook.py
const fixturePath = path.resolve(import.meta.dirname, "../fixtures/akilli-geri-donusum-colab-report.json");
const realReport = fs.readFileSync(fixturePath, "utf-8");
const template = loadContent().colabTemplates.get("akilli-geri-donusum-colab")!;
const expect_ = { projectId: "akilli-geri-donusum", templateId: template.id, notebookVersion: template.version };

const parse = (text: string) => parseTrainingReport(text, new TextEncoder().encode(text).length, expect_);
// Loosely typed on purpose: these tests deliberately write invalid values.
// eslint-disable-next-line @typescript-eslint/no-explicit-any
const mutate = (fn: (r: Record<string, any>) => void) => {
  const r = JSON.parse(realReport);
  fn(r);
  return JSON.stringify(r);
};

describe("training report import", () => {
  it("accepts the report generated by actually running the notebook", () => {
    const result = parse(realReport);
    expect(result.ok, JSON.stringify(result)).toBe(true);
    if (result.ok) {
      expect(result.report.notebook_version).toBe(template.version);
      expect(result.report.experiments.length).toBeGreaterThanOrEqual(4);
      expect(result.warnings).toEqual([]);
    }
  });

  it("rejects files over the size limit before parsing", () => {
    const result = parseTrainingReport("{}", MAX_REPORT_BYTES + 1, expect_);
    expect(result.ok).toBe(false);
  });

  it("rejects non-JSON and non-object input", () => {
    expect(parse("print('merhaba')").ok).toBe(false);
    expect(parse("[1, 2, 3]").ok).toBe(false);
  });

  it("rejects reports for another project or template", () => {
    expect(parse(mutate((r) => (r.project_id = "baska-proje"))).ok).toBe(false);
    expect(parse(mutate((r) => (r.template_id = "baska-defter"))).ok).toBe(false);
  });

  it("rejects an unsupported schema major version and incompatible notebook versions", () => {
    expect(parse(mutate((r) => (r.schema_version = "2.0"))).ok).toBe(false);
    expect(parse(mutate((r) => (r.notebook_version = "2.0.0"))).ok).toBe(false);
  });

  it("accepts a compatible minor notebook version with a warning", () => {
    const result = parse(mutate((r) => (r.notebook_version = "1.9.0")));
    expect(result.ok).toBe(true);
    if (result.ok) expect(result.warnings.length).toBe(1);
  });

  it("rejects out-of-range metrics", () => {
    expect(parse(mutate((r) => (r.test_metrics.accuracy = 1.5))).ok).toBe(false);
    expect(parse(mutate((r) => (r.experiments[0].validation_accuracy = -0.1))).ok).toBe(false);
  });

  it("rejects internally inconsistent reports (accuracy vs confusion matrix)", () => {
    const result = parse(mutate((r) => (r.test_metrics.accuracy = 0.999)));
    expect(result.ok).toBe(false);
    if (!result.ok) expect(result.errors.join(" ")).toMatch(/tutarlı değil/);
  });

  it("rejects a selected experiment that is not in the list", () => {
    expect(parse(mutate((r) => (r.selected_experiment = "yok"))).ok).toBe(false);
  });

  it("drops unknown keys instead of keeping arbitrary payloads", () => {
    const result = parse(mutate((r) => (r.__proto_payload__ = { code: "import os" })));
    expect(result.ok).toBe(true);
    if (result.ok) expect("__proto_payload__" in result.report).toBe(false);
  });

  it("bounds string lengths", () => {
    expect(parse(mutate((r) => (r.experiments[0].algorithm = "x".repeat(5000)))).ok).toBe(false);
  });
});

describe("labs", () => {
  const content = loadContent();

  it("every lesson declares the labs its cells use", () => {
    for (const lesson of content.lessons.values()) expect(lesson.labs).toEqual(labsOfCells(lesson.cells));
  });

  it("the flagship project's builder mode covers all three labs (primary workflow)", () => {
    expect(content.lessons.get("geri-donusum-yapici")!.labs).toEqual(["visual", "python", "colab"]);
  });

  it("rejects a lesson whose labs declaration does not match its cells", () => {
    const raw = JSON.parse(JSON.stringify(content.lessons.get("python-ilk-adimlar")));
    expect(lessonSchema.safeParse({ ...raw, labs: ["visual"] }).success).toBe(false);
  });

  it("classifies cells correctly", () => {
    const lesson = content.lessons.get("geri-donusum-yapici")!;
    const byType = (t: Cell["type"]) => labsOfCells(lesson.cells.filter((c) => c.type === t));
    expect(byType("training")).toEqual(["visual", "python"]); // editable Python copy
    expect(byType("colab")).toEqual(["colab"]);
    expect(byType("reflection")).toEqual([]);
  });
});

describe("Colab launcher", () => {
  it("builds an official Colab GitHub URL only for a valid owner/repo", () => {
    expect(colabOpenUrl(template, "ornek/ai-atolye", "main")).toBe(
      "https://colab.research.google.com/github/ornek/ai-atolye/blob/main/content/colab/akilli-geri-donusum-colab.ipynb",
    );
    expect(colabOpenUrl(template, "", "main")).toBeNull();
    expect(colabOpenUrl(template, "javascript:alert(1)", "main")).toBeNull();
  });

  it("the shipped notebook is valid nbformat 4, Turkish, CPU-only and exports a report", () => {
    const nb = JSON.parse(fs.readFileSync(path.resolve(import.meta.dirname, "../../../../content/colab", template.notebookFile), "utf-8"));
    const source = nb.cells.map((c: { source: string[] }) => c.source.join("")).join("\n");
    expect(nb.nbformat).toBe(4);
    expect(nb.cells.every((c: { outputs?: unknown[] }) => !c.outputs || c.outputs.length === 0)).toBe(true);
    expect(source).toContain("GPU gerekmez");
    expect(source).toContain(`NOTEBOOK_VERSION = "${template.version}"`);
    expect(source).toContain("ai-atolye-rapor.json");
    expect(source).not.toMatch(/pip install|requests\.get|urlopen|wget /);
  });
});

describe("portfolio", () => {
  it("includes the imported Colab result in the project portfolio entry", async () => {
    const { buildPortfolioEntry } = await import("@/lib/notebook/portfolio");
    const { initialCells } = await import("@/lib/notebook/initial");
    const lesson = loadContent().lessons.get("geri-donusum-yapici")!;
    const report = JSON.parse(realReport);
    const cells = { ...initialCells(lesson), colab: { kind: "colab" as const, openedAt: null, report, importedAt: "", fileName: "r.json", warnings: [] } };
    const entry = buildPortfolioEntry(lesson, cells, "2026-10-16T00:00:00Z")!;
    expect(entry.colab?.testAccuracy).toBe(report.test_metrics.accuracy);
    expect(entry.colab?.nTest).toBe(report.dataset.n_test);
  });
});
