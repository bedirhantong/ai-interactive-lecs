"""Database models. Deliberately small: content lives in versioned files, not tables."""

import enum
import uuid
from datetime import UTC, datetime

from sqlalchemy import JSON, DateTime, Enum, ForeignKey, Integer, String, Text, UniqueConstraint, Uuid, false
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column, relationship

# JSONB on PostgreSQL (binary, indexable, deduplicated keys); plain JSON elsewhere (SQLite tests).
JsonDocument = JSON().with_variant(JSONB(), "postgresql")


def utcnow() -> datetime:
    return datetime.now(UTC)


class Base(DeclarativeBase):
    """Migration rule: always give new constraints explicit names in the migration file
    (e.g. uq_users_username), so a downgrade can drop them. Review every autogenerated migration."""


class Role(enum.StrEnum):
    student = "student"
    teacher = "teacher"
    admin = "admin"


class Verification(enum.StrEnum):
    """How much a stored result can be trusted."""

    self_reported = "self_reported"  # computed in the student's browser or Colab session
    teacher_reviewed = "teacher_reviewed"


class MembershipStatus(enum.StrEnum):
    pending = "pending"
    active = "active"


class User(Base):
    __tablename__ = "users"
    id: Mapped[uuid.UUID] = mapped_column(Uuid, primary_key=True, default=uuid.uuid4)
    role: Mapped[Role] = mapped_column(Enum(Role, native_enum=False, length=16))
    display_name: Mapped[str] = mapped_column(String(60))
    # Teachers/admins sign in with email. Students sign in with a username created by their
    # teacher; no email is collected for minors. Both are stored normalized (lowercase).
    email: Mapped[str | None] = mapped_column(String(254), unique=True)
    username: Mapped[str | None] = mapped_column(String(40), unique=True)
    password_hash: Mapped[str | None] = mapped_column(String(200))
    # Set for one-time passwords handed out by a teacher/admin: the user must choose their own first.
    must_change_password: Mapped[bool] = mapped_column(default=False, server_default=false())
    password_changed_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_by_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"))
    age_band: Mapped[str | None] = mapped_column(String(8))  # never a birth date
    is_demo: Mapped[bool] = mapped_column(default=False)
    last_login_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class AuthSession(Base):
    __tablename__ = "sessions"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    token_hash: Mapped[str] = mapped_column(String(64), unique=True, index=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)
    expires_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    revoked_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    user: Mapped[User] = relationship()


class StudentNotebook(Base):
    """Latest snapshot of a student's notebook state (debounced saves, not keystrokes)."""

    __tablename__ = "student_notebooks"
    __table_args__ = (UniqueConstraint("user_id", "lesson_id"),)
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    lesson_id: Mapped[str] = mapped_column(String(80))
    lesson_version: Mapped[int] = mapped_column(Integer)
    # Optimistic concurrency: +1 on every save; clients send it back in If-Match.
    revision: Mapped[int] = mapped_column(Integer, default=1, server_default="1")
    state: Mapped[dict] = mapped_column(JsonDocument)
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, onupdate=utcnow)


class ProgressEvent(Base):
    """Evidence of learning (cell completed, model trained, ...). Always self-reported for now."""

    __tablename__ = "progress_events"
    # Retried uploads carry the same client id and are ignored (idempotent ingestion).
    __table_args__ = (UniqueConstraint("user_id", "client_event_id", name="uq_progress_events_user_id_client_event_id"),)
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    client_event_id: Mapped[str | None] = mapped_column(String(64))
    lesson_id: Mapped[str] = mapped_column(String(80), index=True)
    cell_id: Mapped[str] = mapped_column(String(80))
    kind: Mapped[str] = mapped_column(String(40))
    detail: Mapped[str] = mapped_column(String(300))
    verification: Mapped[Verification] = mapped_column(Enum(Verification, native_enum=False, length=24), default=Verification.self_reported)
    occurred_at: Mapped[datetime] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class TrainingReport(Base):
    """A Colab training report uploaded by a student. Validated JSON only; never executed."""

    __tablename__ = "training_reports"
    # The same report uploaded twice (e.g. a retry) is stored once.
    __table_args__ = (UniqueConstraint("user_id", "lesson_id", "content_hash", name="uq_training_reports_user_id_lesson_id_content_hash"),)
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    content_hash: Mapped[str | None] = mapped_column(String(64))
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    lesson_id: Mapped[str] = mapped_column(String(80))
    project_id: Mapped[str] = mapped_column(String(80))
    template_id: Mapped[str] = mapped_column(String(80))
    notebook_version: Mapped[str] = mapped_column(String(20))
    test_accuracy: Mapped[float]
    report: Mapped[dict] = mapped_column(JsonDocument)
    verification: Mapped[Verification] = mapped_column(Enum(Verification, native_enum=False, length=24), default=Verification.self_reported)
    teacher_note: Mapped[str | None] = mapped_column(Text)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class Classroom(Base):
    __tablename__ = "classrooms"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    teacher_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    name: Mapped[str] = mapped_column(String(80))
    join_code: Mapped[str] = mapped_column(String(12), unique=True, index=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class ClassroomMembership(Base):
    """Students join with a code; a teacher must approve before they see anything or are seen."""

    __tablename__ = "classroom_memberships"
    __table_args__ = (UniqueConstraint("classroom_id", "user_id"),)
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    classroom_id: Mapped[int] = mapped_column(ForeignKey("classrooms.id", ondelete="CASCADE"), index=True)
    user_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("users.id", ondelete="CASCADE"), index=True)
    status: Mapped[MembershipStatus] = mapped_column(Enum(MembershipStatus, native_enum=False, length=16), default=MembershipStatus.pending)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class Assignment(Base):
    __tablename__ = "assignments"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    classroom_id: Mapped[int] = mapped_column(ForeignKey("classrooms.id", ondelete="CASCADE"), index=True)
    lesson_id: Mapped[str] = mapped_column(String(80))
    due_at: Mapped[datetime | None] = mapped_column(DateTime(timezone=True))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow)


class AuthAttempt(Base):
    """Login and demo-account attempts, for rate limiting across all API instances.

    Identifiers and IP addresses are stored only as keyed hashes (HMAC), never in clear text.
    Old rows are deleted by `python -m app.cli cleanup`.
    """

    __tablename__ = "auth_attempts"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    action: Mapped[str] = mapped_column(String(20))
    key_hash: Mapped[str] = mapped_column(String(64), index=True)
    ip_hash: Mapped[str] = mapped_column(String(64), index=True)
    succeeded: Mapped[bool]
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)


class AuditEvent(Base):
    """Who did what to whose data: teacher access to student data, account changes, exports, deletions.

    Students can read the events about themselves (GET /me/access-log). If an account is deleted, its
    references become NULL, so the event stays but no longer identifies that person.
    Deleted after ATOLYE_AUDIT_RETENTION_DAYS by `python -m app.cli cleanup`.
    """

    __tablename__ = "audit_events"
    id: Mapped[int] = mapped_column(Integer, primary_key=True)
    action: Mapped[str] = mapped_column(String(40), index=True)
    actor_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"), index=True)
    actor_role: Mapped[str | None] = mapped_column(String(16))
    subject_id: Mapped[uuid.UUID | None] = mapped_column(ForeignKey("users.id", ondelete="SET NULL"), index=True)
    classroom_id: Mapped[int | None] = mapped_column(ForeignKey("classrooms.id", ondelete="SET NULL"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, index=True)
